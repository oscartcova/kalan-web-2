async function analyzeVigencia({ file, useSample }) {
  const contentBlocks = [];

  if (useSample || !file) {
    contentBlocks.push({ type: "text", text: "Documento a analizar:\n\n" + SAMPLE_ID_TEXT });
  } else if (file.type === "application/pdf") {
    const base64 = await fileToBase64(file);
    contentBlocks.push({ type: "document", source: { type: "base64", media_type: "application/pdf", data: base64 } });
  } else if (file.type && file.type.startsWith("image/")) {
    const base64 = await fileToBase64(file);
    contentBlocks.push({ type: "image", source: { type: "base64", media_type: file.type, data: base64 } });
  } else {
    throw new Error("Ese tipo de archivo no lo podemos leer.");
  }

  contentBlocks.push({ type: "text", text: buildVigenciaInstructions() });

  const response = await fetchWithRetry({
    model: "claude-sonnet-4-6",
    max_tokens: 600,
    messages: [{ role: "user", content: contentBlocks }],
  });

  const data = await response.json();
  const textBlock = (data.content || []).find((b) => b.type === "text");
  if (!textBlock || !textBlock.text) {
    throw new Error("El analizador no devolvió una respuesta.");
  }

  const cleaned = textBlock.text.replace(/```json|```/g, "").trim();
  let parsed;
  try {
    parsed = JSON.parse(cleaned);
  } catch (e) {
    throw new Error("No entendimos el resultado del análisis.");
  }

  if (!parsed.documento || !parsed.estado) {
    throw new Error("El resultado no tiene el formato esperado.");
  }
  return parsed;
}


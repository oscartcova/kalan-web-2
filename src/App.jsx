function TramiteGuideScreen({ tramite, largeText }) {
  const base = largeText ? 18.5 : 16.5;
  const sub = largeText ? 16 : 14;
  const h = largeText ? 22 : 19;
  const [done, setDone] = useState(() => tramite.pasos.map(() => false));
  const [openIndex, setOpenIndex] = useState(null);

  const toggleDone = (i) => setDone((d) => d.map((v, idx) => (idx === i ? !v : v)));
  const completedCount = done.filter(Boolean).length;

  return (
    <div style={{ padding: "12px 22px 26px" }}>
      <div style={{ fontFamily: "'Source Serif 4', serif", fontWeight: 700, fontSize: h, color: TOKENS.ink, marginBottom: 6 }}>{tramite.titulo}</div>
      <div style={{ fontFamily: "Inter, sans-serif", fontSize: sub, color: TOKENS.textMuted, lineHeight: 1.5, marginBottom: 14 }}>{tramite.descripcion}</div>

      <a
        href={tramite.sitioOficial}
        target="_blank"
        rel="noreferrer"
        style={{ display: "flex", alignItems: "center", justifyContent: "center", gap: 8, background: TOKENS.ink, color: "#FFF", borderRadius: 14, padding: "13px", fontFamily: "Inter, sans-serif", fontWeight: 600, fontSize: sub, textDecoration: "none", marginBottom: 16 }}
      >
        <ExternalLink size={16} /> Abrir sitio oficial
      </a>

      {tramite.documentos && tramite.documentos.length > 0 && (
        <Card>
          <div style={{ fontFamily: "Inter, sans-serif", fontWeight: 700, fontSize: sub, color: TOKENS.ink, marginBottom: 8 }}>Antes de empezar</div>
          <ul style={{ margin: 0, paddingLeft: 20 }}>
            {tramite.documentos.map((d, i) => (
              <li key={i} style={{ fontFamily: "Inter, sans-serif", fontSize: sub, color: TOKENS.text, lineHeight: 1.5 }}>{d}</li>
            ))}
          </ul>
        </Card>
      )}

      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", margin: "18px 2px 10px" }}>
        <div style={{ fontFamily: "Inter, sans-serif", fontWeight: 700, fontSize: sub, color: TOKENS.ink }}>Pasos a seguir</div>
        <div style={{ fontFamily: "Inter, sans-serif", fontSize: sub - 1, color: TOKENS.textMuted }}>{completedCount} de {tramite.pasos.length}</div>
      </div>

      <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
        {tramite.pasos.map((p, i) => (
          <div key={i} style={{ background: "#FFFFFF", border: `1px solid ${TOKENS.paperDark}`, borderRadius: 14, padding: "14px 16px", opacity: done[i] ? 0.6 : 1 }}>
            <div style={{ display: "flex", gap: 12, alignItems: "flex-start" }}>
              <button onClick={() => toggleDone(i)} aria-label={done[i] ? "Marcar como pendiente" : "Marcar como hecho"} style={{ background: "none", border: "none", cursor: "pointer", padding: 0, marginTop: 1, flexShrink: 0 }}>
                {done[i] ? <CheckCircle2 size={22} color={TOKENS.forest} /> : <Circle size={22} color={TOKENS.textMuted} />}
              </button>
              <div style={{ flex: 1 }}>
                <div
                  onClick={() => setOpenIndex(openIndex === i ? null : i)}
                  style={{ display: "flex", justifyContent: "space-between", alignItems: "center", cursor: "pointer" }}
                >
                  <div style={{ fontFamily: "Inter, sans-serif", fontWeight: 600, fontSize: base, color: TOKENS.ink, textDecoration: done[i] ? "line-through" : "none" }}>
                    {i + 1}. {p.titulo}
                  </div>
                  <ChevronRight size={18} color={TOKENS.textMuted} style={{ transform: openIndex === i ? "rotate(90deg)" : "none", transition: "transform 0.2s", flexShrink: 0 }} />
                </div>
                {openIndex === i && (
                  <div style={{ marginTop: 8, fontFamily: "Inter, sans-serif", fontSize: sub, color: TOKENS.text, lineHeight: 1.5 }}>{p.detalle}</div>
                )}
              </div>
            </div>
          </div>
        ))}
      </div>

      {completedCount === tramite.pasos.length && (
        <div style={{ marginTop: 16, background: "#E9F6EE", border: `1px solid ${TOKENS.forest}`, borderRadius: 14, padding: "14px 16px", display: "flex", gap: 10, alignItems: "center" }}>
          <CheckCircle2 size={22} color={TOKENS.forest} style={{ flexShrink: 0 }} />
          <div style={{ fontFamily: "Inter, sans-serif", fontSize: sub, color: TOKENS.text, lineHeight: 1.5 }}>¡Completaste todos los pasos! Ya deberías tener tu documento listo.</div>
        </div>
      )}

      <button style={{ width: "100%", marginTop: 16, display: "flex", alignItems: "center", justifyContent: "center", gap: 8, background: "#FFFFFF", border: `2px solid ${TOKENS.ink}`, borderRadius: 14, padding: "13px", fontFamily: "Inter, sans-serif", fontWeight: 600, fontSize: sub, color: TOKENS.ink, cursor: "pointer" }}>
        <Share2 size={18} /> Compartir esta guía
      </button>
    </div>
  );
}

export default function KalanApp() {
  const [screen, setScreen] = useState("home");
  const [mode, setMode] = useState("contract");
  const [largeText, setLargeText] = useState(false);
  const [fileName, setFileName] = useState("");
  const [selectedFile, setSelectedFile] = useState(null);
  const [useSample, setUseSample] = useState(false);
  const [willFail, setWillFail] = useState(false);
  const [analysisResult, setAnalysisResult] = useState(null);
  const [errorReason, setErrorReason] = useState("blurry");
  const [showPrivacy, setShowPrivacy] = useState(false);
  const [selectedTramiteId, setSelectedTramiteId] = useState(null);

  const onStartContract = () => {
    setMode("contract");
    setScreen("upload");
  };
  const onStartVigencia = () => {
    setMode("vigencia");
    setScreen("upload");
  };
  const onStartTramites = () => setScreen("tramites");
  const onSelectTramite = (id) => {
    setSelectedTramiteId(id);
    setScreen("tramiteGuide");
  };

  const onSelectReal = (file) => {
    setSelectedFile(file);
    setFileName(file.name);
    setUseSample(false);
    setWillFail(false);
    setScreen("confirm");
  };
  const onSelectSample = () => {
    setSelectedFile(null);
    setFileName(mode === "vigencia" ? "identificacion_ejemplo.jpg" : "contrato_ejemplo.pdf");
    setUseSample(true);
    setWillFail(false);
    setScreen("confirm");
  };
  const onSimulateBlurry = () => {
    setSelectedFile(null);
    setFileName("foto_borrosa.jpg");
    setUseSample(false);
    setWillFail(true);
    setScreen("confirm");
  };

  const startProcessing = async () => {
    setScreen("processing");
    if (willFail) {
      setTimeout(() => {
        setErrorReason("blurry");
        setScreen("error");
      }, 2200);
      return;
    }
    try {
      const result =
        mode === "vigencia"
          ? await analyzeVigencia({ file: selectedFile, useSample })
          : await analyzeContract({ file: selectedFile, useSample });
      setAnalysisResult(result);
      setScreen("summary");
    } catch (err) {
      console.error(err);
      setErrorReason("api");
      setScreen("error");
    }
  };

  const reset = () => {
    setScreen("home");
    setFileName("");
    setSelectedFile(null);
    setUseSample(false);
    setWillFail(false);
    setAnalysisResult(null);
  };
  const retryFromError = () => {
    setWillFail(false);
    setScreen("upload");
  };

  const titles = {
    home: "",
    upload: mode === "vigencia" ? "Verificar documento" : "Nuevo contrato",
    confirm: "Confirmar",
    processing: "Analizando",
    error: "Necesitamos tu ayuda",
    summary: mode === "vigencia" ? "Resultado" : "Tu resumen",
    tramites: "Trámites en línea",
    tramiteGuide: "Guía paso a paso",
  };

  const stepIndex = { upload: 0, confirm: 1, processing: 2, summary: 3 }[screen];

  const backHandlers = {
    upload: () => setScreen("home"),
    confirm: () => setScreen("upload"),
    error: () => setScreen("upload"),
    summary: reset,
    tramites: () => setScreen("home"),
    tramiteGuide: () => setScreen("tramites"),
  };

  return (
    <div style={{ minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center", background: "#D9DFEC", fontFamily: "Inter, sans-serif", padding: "24px 12px" }}>
      <style>{FONTS}</style>
      <div style={{ width: 390, maxWidth: "100%", minHeight: 720, background: TOKENS.paper, borderRadius: 34, border: `8px solid #16326B`, overflow: "hidden", boxShadow: "0 20px 50px rgba(0,0,0,0.25)", display: "flex", flexDirection: "column", position: "relative" }}>
        {screen !== "home" && (
          <TopBar
            title={titles[screen]}
            onBack={backHandlers[screen] || null}
            largeText={largeText}
            setLargeText={setLargeText}
            showTextToggle={screen !== "processing"}
            onOpenPrivacy={() => setShowPrivacy(true)}
          />
        )}
        {stepIndex !== undefined && <StepIndicator currentIndex={stepIndex} />}
        <div style={{ flex: 1, overflowY: "auto" }}>
          {screen === "home" && (
            <HomeScreen onStartContract={onStartContract} onStartVigencia={onStartVigencia} onStartTramites={onStartTramites} largeText={largeText} setLargeText={setLargeText} onOpenPrivacy={() => setShowPrivacy(true)} />
          )}
          {screen === "upload" && (
            <UploadScreen onSelectReal={onSelectReal} onSelectSample={onSelectSample} onSimulateBlurry={onSimulateBlurry} largeText={largeText} mode={mode} />
          )}
          {screen === "confirm" && (
            <ConfirmScreen fileName={fileName} onConfirm={startProcessing} onChangeFile={() => setScreen("upload")} largeText={largeText} mode={mode} />
          )}
          {screen === "processing" && <ProcessingScreen mode={mode} />}
          {screen === "error" && <ErrorScreen onRetry={retryFromError} largeText={largeText} reason={errorReason} />}
          {screen === "summary" && analysisResult && mode === "contract" && <SummaryScreen largeText={largeText} onReset={reset} result={analysisResult} />}
          {screen === "summary" && analysisResult && mode === "vigencia" && <VigenciaSummaryScreen largeText={largeText} onReset={reset} result={analysisResult} />}
          {screen === "tramites" && <TramiteListScreen onSelect={onSelectTramite} largeText={largeText} />}
          {screen === "tramiteGuide" && selectedTramiteId && (
            <TramiteGuideScreen tramite={TRAMITES.find((t) => t.id === selectedTramiteId)} largeText={largeText} />
          )}
        </div>
        {screen === "home" && (
          <div style={{ display: "flex", justifyContent: "center", padding: "10px 0 16px", color: TOKENS.textMuted }}>
            <HomeIcon size={18} />
          </div>
        )}
        {showPrivacy && <PrivacyModal onClose={() => setShowPrivacy(false)} largeText={largeText} />}
      </div>
    </div>
  );
}
